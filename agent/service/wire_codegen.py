"""Render the Desktop TypeScript wire types from ``wire_schema``.

Output is deterministic so a test can assert the committed
``wire.generated.ts`` is current.  Run ``python scripts/gen_wire_types.py``
after changing a wire contract.
"""

from __future__ import annotations

import ast
import dataclasses
import enum
import inspect
import textwrap
import types
import typing
from collections.abc import Mapping, Sequence
from pathlib import Path

from .local_protocol import LOCAL_TRANSPORT_METHODS
from .wire_schema import WIRE_METHODS

TS_OUTPUT = (
    Path(__file__).resolve().parents[2]
    / "apps" / "desktop" / "src" / "service" / "wire.generated.ts"
)

_HEADER = """\
// GENERATED by scripts/gen_wire_types.py from agent/service/wire_schema.py.
// Do not edit by hand — change the Python contract and regenerate.
/* eslint-disable */
"""


def _is_typeddict(tp: object) -> bool:
    return isinstance(tp, type) and typing.is_typeddict(tp)


def to_dict_keys(cls: type) -> set[str]:
    """Literal keys a contract's hand-written ``to_dict`` emits (MRO-wide)."""
    keys: set[str] = set()
    for klass in cls.__mro__:
        func = klass.__dict__.get("to_dict")
        if func is None:
            continue
        tree = ast.parse(textwrap.dedent(inspect.getsource(func)))
        for node in ast.walk(tree):
            if isinstance(node, ast.Dict):
                keys |= {k.value for k in node.keys if isinstance(k, ast.Constant)}
            elif isinstance(node, ast.Subscript) and isinstance(node.ctx, ast.Store):
                if isinstance(node.slice, ast.Constant):
                    keys.add(node.slice.value)
    return keys


def wire_properties(cls: type) -> dict[str, object]:
    """Computed properties ``to_dict`` serializes alongside the fields."""
    if not hasattr(cls, "to_dict"):
        return {}
    emitted = to_dict_keys(cls)
    return {
        name: typing.get_type_hints(member.fget)["return"]
        for name, member in inspect.getmembers(cls)
        if isinstance(member, property) and name in emitted
    }


class _Renderer:
    """``role`` is "params" or "result": a params dataclass field with a
    default is optional on the wire, while a result's ``to_dict`` always
    emits every field (asserted by tests/test_wire_schema.py)."""

    def __init__(self) -> None:
        self._declared: dict[str, str] = {}
        self._roles: dict[str, str] = {}

    def type_ref(self, tp: object, role: str) -> str:
        if tp is typing.Any or tp is object:
            return "unknown"
        if tp is type(None) or tp is None:
            return "null"
        if tp is str:
            return "string"
        if tp is bool:
            return "boolean"
        if tp in (int, float):
            return "number"
        origin = typing.get_origin(tp)
        args = typing.get_args(tp)
        if origin in (typing.Union, types.UnionType):
            return " | ".join(dict.fromkeys(self.type_ref(arg, role) for arg in args))
        if origin is typing.Literal:
            return " | ".join(f'"{arg}"' for arg in args)
        if origin in (list, tuple, Sequence, set, frozenset):
            item = args[0] if args else typing.Any
            inner = self.type_ref(item, role)
            return f"({inner})[]" if " | " in inner else f"{inner}[]"
        if origin in (dict, Mapping) or tp in (dict, Mapping):
            value = args[1] if len(args) == 2 else typing.Any
            return f"Record<string, {self.type_ref(value, role)}>"
        if isinstance(tp, type) and issubclass(tp, enum.Enum):
            return " | ".join(f'"{member.value}"' for member in tp)
        if isinstance(tp, type) and (dataclasses.is_dataclass(tp) or _is_typeddict(tp)):
            return self._declare(tp, role)
        raise TypeError(f"unsupported wire type: {tp!r}")

    def _declare(self, tp: type, role: str) -> str:
        name = f"Wire{tp.__name__}"
        if name in self._declared:
            if self._roles[name] != role:
                raise TypeError(f"{tp.__name__} is used as both wire params and result")
            return name
        self._roles[name] = role
        self._declared[name] = ""  # reserve before recursing
        hints = typing.get_type_hints(tp)
        lines: list[str] = []
        if dataclasses.is_dataclass(tp):
            for item in dataclasses.fields(tp):
                optional = role == "params" and (
                    item.default is not dataclasses.MISSING
                    or item.default_factory is not dataclasses.MISSING
                )
                lines.append(self._field(item.name, hints[item.name], optional, role))
            for key, hint in wire_properties(tp).items():
                lines.append(self._field(key, hint, False, role))
        else:
            for key, hint in hints.items():
                lines.append(self._field(key, hint, key in tp.__optional_keys__, role))
        body = "\n".join(lines)
        self._declared[name] = (
            f"export interface {name} {{\n{body}\n}}" if body else f"export type {name} = Record<string, never>;"
        )
        return name

    def _field(self, key: str, hint: object, optional: bool, role: str) -> str:
        return f"  {key}{'?' if optional else ''}: {self.type_ref(hint, role)};"

    def declarations(self) -> str:
        return "\n\n".join(self._declared[name] for name in sorted(self._declared))


def render_typescript() -> str:
    renderer = _Renderer()
    entries: list[str] = []
    for method in LOCAL_TRANSPORT_METHODS:
        spec = WIRE_METHODS[next(m for m in WIRE_METHODS if m.value == method)]
        params = renderer.type_ref(spec.params, "params")
        result = renderer.type_ref(spec.result, "result")
        entries.append(f"  {method}: {{ params: {params}; result: {result} }};")
    methods = ",\n".join(f'  "{method}"' for method in LOCAL_TRANSPORT_METHODS)
    return (
        _HEADER
        + f"\nexport const LOCAL_TRANSPORT_METHODS = [\n{methods},\n] as const;\n"
        + "\nexport type LocalTransportMethod = (typeof LOCAL_TRANSPORT_METHODS)[number];\n"
        + "\nexport interface WireMethods {\n" + "\n".join(entries) + "\n}\n"
        + "\nexport type WireParams<M extends LocalTransportMethod> = WireMethods[M][\"params\"];\n"
        + "export type WireResult<M extends LocalTransportMethod> = WireMethods[M][\"result\"];\n"
        + "\n" + renderer.declarations() + "\n"
    )



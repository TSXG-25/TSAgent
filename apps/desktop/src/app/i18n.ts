import { useSyncExternalStore } from "react";

/** App-wide UI language — zh-CN / en. Default follows the system language
 *  (non-Chinese systems get English); the user's choice persists locally.
 *  Covers shell chrome, status, forms and prompts only — user content, model
 *  output and file names always render verbatim. */
export type Lang = "zh" | "en";

const STORAGE_KEY = "tsagent:lang";
const listeners = new Set<() => void>();

export function getLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "zh" || saved === "en") return saved;
  } catch { /* storage unavailable */ }
  const sys = typeof navigator !== "undefined" ? navigator.language ?? "" : "";
  return sys.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function setLang(lang: Lang): void {
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* quota */ }
  listeners.forEach((fn) => fn());
}

export function useLang(): Lang {
  return useSyncExternalStore((cb) => {
    listeners.add(cb);
    return () => listeners.delete(cb);
  }, getLang);
}


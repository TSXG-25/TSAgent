export type I18nKey = keyof typeof zh;
const dict: Record<Lang, Record<I18nKey, string>> = { zh, en };

/** Lookup only — returns undefined when the key is absent (e.g. error codes
 *  without a localized summary), letting callers fall back to the raw code. */
export function tk(key: string, lang: Lang = getLang()): string | undefined {
  return dict[lang][key as I18nKey] ?? dict.en[key as I18nKey];
}

/** Localized UI string; `{name}` placeholders interpolate from params. */
export function t(key: I18nKey, params?: Record<string, string | number>, lang: Lang = getLang()): string {
  let s = dict[lang][key] ?? dict.en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}
